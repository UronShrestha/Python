'''Accessing Elements
Elements in a list are accessed using indexing. Python uses zero-based indexing, 
meaning a[0] represents the first element. Negative indexing is also supported, 
where -1 accesses the last element.'''

a = [10,20,30]
print(a)
print(a[0])
print(a[1])
print(a[2])
print(a[-1])
print(a[-2])
print(a[-3])